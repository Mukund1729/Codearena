function mapDifficulty(stats) {
  const ratio = stats.solved / stats.tried;
  if (ratio > 0.7) return 'EASY';
  if (ratio > 0.4) return 'MEDIUM';
  return 'HARD';
}

function mapTags(tags) {
  return tags.map(t => t.toLowerCase().replace(/\s+/g, '-')).join(',');
}

function convertProblem(p) {
  const stats = { solved: p.solved, tried: p.tried };
  return {
    id: p.id,
    title: p.title,
    slug: p.id,
    description: p.description,
    input_format: p.input,
    output_format: p.output,
    constraints: p.limits,
    sample_input: p.sample_input,
    sample_output: p.sample_output,
    difficulty: mapDifficulty(stats),
    tags: mapTags(p.tags),
    time_limit: 1000,
    memory_limit: 256,
    total_test_cases: 5,
    status: 'PUBLISHED',
    points: p.tags.includes('brute-force') || p.tags.includes('sorting') ? 10 : 5,
    acceptance_rate: Math.round((stats.solved / stats.tried) * 100),
    created_by: 'kattis-import',
    source: 'Kattis',
    url: `${KATTIS_BASE}/problems/${p.id}`,
  };
}

function main() {
  const limit = process.argv[2] ? parseInt(process.argv[2], 10) : CURATED_PROBLEMS.length;
  const outputFile = path.join(__dirname, 'kattis-problems.json');
  const problems = CURATED_PROBLEMS.slice(0, limit).map(convertProblem);

  fs.writeFileSync(outputFile, JSON.stringify(problems, null, 2));
  console.log(`Saved ${problems.length} Kattis problems to ${outputFile}`);
  problems.forEach(p => console.log(`  - ${p.title} (${p.difficulty})`));
}

main();
